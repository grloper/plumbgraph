    fn ex(pack: &str, path: &str, src: &str) -> FileFacts {
        let set = PackSet::builtin().unwrap();
        extract(set.by_id(pack).unwrap(), path, src).unwrap()
    }
    fn sym<'a>(f: &'a FileFacts, name: &str) -> &'a SymbolFact {
        f.symbols
            .iter()
            .find(|s| s.name == name)
            .unwrap_or_else(|| {
                panic!(
                    "no symbol {name}: {:?}",
                    f.symbols.iter().map(|s| &s.name).collect::<Vec<_>>()
                )
            })
    }

    #[test]
    fn python_symbols_imports_refs() {
        let f = ex(
            "python",
            "pkg/mod.py",
            "import os, json as j\nfrom .util import helper as h, other\nfrom pkg.sub import thing\n\nclass Foo:\n    def __init__(self):\n        self.x = helper()\n    def bar(self):\n        return self.baz()\n    def _priv(self): pass\n\n@app.route('/x')\ndef view():\n    return Foo().bar()\n\ndef _unused(): pass\n",
        );
        assert_eq!(sym(&f, "Foo").kind, "class");
        assert_eq!(sym(&f, "bar").kind, "method");
        assert_eq!(sym(&f, "bar").qname, "Foo.bar");
        assert!(sym(&f, "bar").exported);
        assert!(!sym(&f, "_priv").exported);
        assert_eq!(sym(&f, "__init__").entry.as_deref(), Some("dunder method"));
        assert!(sym(&f, "view").decorated);
        assert!(!sym(&f, "_unused").exported);
        let mods: Vec<_> = f.imports.iter().map(|i| i.module.as_str()).collect();
        assert!(
            mods.contains(&"os")
                && mods.contains(&"json")
                && mods.contains(&".util")
                && mods.contains(&"pkg.sub"),
            "{mods:?}"
        );
        let util = f.imports.iter().find(|i| i.module == ".util").unwrap();
        assert_eq!(util.names, vec!["helper".to_string(), "other".to_string()]);
        // `helper()` call inside __init__ is a call ref enclosed by __init__
        let r = f.refs.iter().find(|r| r.name == "helper").unwrap();
        assert_eq!(r.kind, "calls");
        assert_eq!(f.symbols[r.src.unwrap()].name, "__init__");
        // self.baz() is a member call
        let b = f.refs.iter().find(|r| r.name == "baz").unwrap();
        assert!(b.member && b.kind == "calls");
        // imported names are not counted as references
        assert!(!f.refs.iter().any(|r| r.name == "thing"));
    }

