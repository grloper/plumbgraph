fn globset(patterns: &[String]) -> GlobSet {
    let mut b = GlobSetBuilder::new();
    for p in patterns {
        if let Ok(g) = Glob::new(p) {
            b.add(g);
        }
    }
    b.build().unwrap_or_else(|_| GlobSet::empty())
}

/// Is `rel_path` a test (or example/bench) file according to the pack's globs?
pub fn is_test_path(pack: &Pack, rel_path: &str) -> bool {
    globset(&pack.manifest.test_globs).is_match(rel_path)
}

fn looks_generated(rel_path: &str, text: &str) -> bool {
    let lower = rel_path.to_ascii_lowercase();
    if lower.ends_with(".min.js")
        || lower.ends_with(".d.ts")
        || lower.ends_with(".d.mts")
        || lower.ends_with(".d.cts")
        || lower.ends_with(".pb.go")
    {
        return true;
    }
    text.lines().take(10).any(|l| {
        l.contains("@generated")
            || l.contains("DO NOT EDIT")
            || l.contains("Code generated")
            || l.contains("auto-generated")
            || l.contains("autogenerated")
    })
}

fn is_ident_like(s: &str) -> bool {
    let mut chars = s.chars();
    match chars.next() {
        Some(c) if c.is_alphabetic() || c == '_' || c == '$' => {}
        _ => return false,
    }
    s.len() <= 64 && chars.all(|c| c.is_alphanumeric() || c == '_' || c == '$')
}

struct RawDef<'t> {
    pat: usize,
    kind: String,
    def: Node<'t>,
    name_node: Node<'t>,
}

fn text<'a>(n: Node, src: &'a [u8]) -> &'a str {
    std::str::from_utf8(&src[n.start_byte()..n.end_byte()]).unwrap_or("")
}

fn rust_attrs(def: Node, src: &[u8]) -> Vec<String> {
    let mut out = vec![];
    let mut cur = def.prev_sibling();
    while let Some(s) = cur {
        match s.kind() {
            "attribute_item" => out.push(text(s, src).trim().to_string()),
            "line_comment" | "block_comment" => {}
            _ => break,
        }
        cur = s.prev_sibling();
    }
    out
}

fn attr_inner(a: &str) -> &str {
    a.trim()
        .trim_start_matches("#[")
        .trim_end_matches(']')
        .trim()
}

fn rust_attr_is_test(inner: &str) -> bool {
    inner == "test"
        || inner.ends_with("::test")
        || inner.contains("cfg(test)")
        || inner.starts_with("test_case")
        || inner == "bench"
}

